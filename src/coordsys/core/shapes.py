"""Геометрия демонстрационных объектов.

Объекты намеренно асимметричны: у 2D-фигуры разные по длине "лапы", у 3D-каркаса
разная высота граней. Это нужно, чтобы на рисунке были видны любые повороты и
отражения — симметричная фигура (например, правильный треугольник) могла бы
выглядеть одинаково в двух разных ориентациях, и пользователь не смог бы
по-честному сверить свой ответ с картинкой.

Координаты заданы как обычные (не однородные) точки — однородная добавка
(единичная координата w) появляется только в слое ``transforms``, непосредственно
перед умножением на матрицу преобразования.
"""

from __future__ import annotations

Point2D = tuple[float, float]
Point3D = tuple[float, float, float]


def demo_polygon_2d() -> list[Point2D]:
    """Асимметричный многоугольник-"флажок" для режима 2.

    Форма похожа на стрелку: длинный "хвост" вдоль оси X и смещённый
    треугольный "наконечник" — при повороте или отражении сразу видно,
    куда сейчас смотрит фигура.
    """

    return [
        (0.0, 0.0),
        (3.0, 0.0),
        (3.0, 1.0),
        (4.5, -0.5),
        (3.0, -2.0),
        (3.0, -1.0),
        (0.0, -1.0),
    ]


def demo_wireframe_3d() -> tuple[list[Point3D], list[tuple[int, int]]]:
    """Асимметричный каркасный объект для режима 3 ("домик" с перекосом).

    Returns:
        Кортеж ``(вершины, рёбра)``, где рёбра — пары индексов вершин.
        Прямоугольное основание плюс смещённая вершина крыши делают
        объект несимметричным по всем трём осям.
    """

    vertices: list[Point3D] = [
        (0.0, 0.0, 0.0),  # 0 — основание
        (2.0, 0.0, 0.0),  # 1
        (2.0, 1.0, 0.0),  # 2
        (0.0, 1.0, 0.0),  # 3
        (0.0, 0.0, 1.5),  # 4 — стены
        (2.0, 0.0, 1.5),  # 5
        (2.0, 1.0, 1.5),  # 6
        (0.0, 1.0, 1.5),  # 7
        (0.3, 0.8, 2.6),  # 8 — смещённый конёк крыши
    ]
    edges = [
        (0, 1), (1, 2), (2, 3), (3, 0),  # основание
        (4, 5), (5, 6), (6, 7), (7, 4),  # верх стен
        (0, 4), (1, 5), (2, 6), (3, 7),  # вертикальные рёбра
        (4, 8), (5, 8), (6, 8), (7, 8),  # скаты крыши к коньку
    ]
    return vertices, edges
