"""Понятие ориентации (хиральности) трёхмерной системы координат.

Система координат называется правой, если кратчайший поворот от оси X
к оси Y (если смотреть с положительного конца оси Z) происходит против
часовой стрелки — это же правило "правой руки". Если направление
поворота меняется на противоположное (например, за счёт отражения одной
из осей), система становится левой.

Поворот сам по себе ориентацию не меняет — меняет её только отражение
(нечётное число инвертированных осей). Поэтому для режима 1 мы сначала
решаем, левая система или правая (отражением оси Z при необходимости),
и только потом применяем случайный поворот.
"""

from __future__ import annotations

import enum
import random
from dataclasses import dataclass


class Handedness(enum.Enum):
    """Хиральность системы координат."""

    RIGHT = "правая"
    LEFT = "левая"


@dataclass(frozen=True)
class RandomTrial:
    """Описание случайного испытания для режима 1 (угадайки).

    Attributes:
        handedness: какая система координат была сгенерирована на самом деле.
        angles_deg: случайные углы поворота (в градусах) вокруг X, Y и Z,
            которые применяются к базовым осям перед отрисовкой — чтобы
            по рисунку нельзя было узнать ориентацию "по умолчанию".
    """

    handedness: Handedness
    angles_deg: tuple[float, float, float]


def random_trial(rng: random.Random | None = None) -> RandomTrial:
    """Генерирует случайную ориентацию и случайный поворот для режима 1.

    Args:
        rng: источник случайности; по умолчанию используется глобальный
            модуль ``random`` (удобно для воспроизводимости в тестах, если
            они понадобятся).

    Returns:
        Случайное испытание: ориентация + углы поворота по трём осям.
    """

    rng = rng or random
    handedness = rng.choice([Handedness.RIGHT, Handedness.LEFT])
    angles_deg = (
        rng.uniform(0, 360),
        rng.uniform(0, 360),
        rng.uniform(0, 360),
    )
    return RandomTrial(handedness=handedness, angles_deg=angles_deg)
